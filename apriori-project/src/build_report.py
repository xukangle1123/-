def draw_table(pdf, headers, rows, widths, align=None):
    """通用表格 | Универсальная таблица."""
    pdf.set_font(FONT_FAMILY, "B", 10)
    pdf.set_fill_color(31, 78, 121)
    pdf.set_text_color(255, 255, 255)
    for i, h in enumerate(headers):
        pdf.cell(widths[i], 7, h, border=1, fill=True, align="C")
    pdf.ln()
    pdf.set_font(FONT_FAMILY, "", 10)
    pdf.set_text_color(0, 0, 0)
    pdf.set_fill_color(235, 240, 248)
    for r_i, row in enumerate(rows):
        if r_i % 2 == 0:
            fill = True
        else:
            fill = False
        for i, cell in enumerate(row):
            a = align[i] if align else "C"
            pdf.cell(widths[i], 7, str(cell), border=1, fill=fill, align=a)
        pdf.ln()


